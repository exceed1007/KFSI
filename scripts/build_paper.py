    # ==================== 4 关键字段识别 ====================
    b.h1('4 关键字段识别')
    b.p('本节给出两类关键字段的可计算判据。判据的设计原则是“一条判据对应'
        '一条协议设计约束”，避免判据的堆砌；每条判据的必要性均在消融实验'
        '中逐一关闭确认（见后文实验部分）。')
    b.h2('4.1 结构标识字段')
    b.p('结构标识字段（Structure Identifier Field，SIF）的三条设计特征是：'
        '位置在前、取值有限、决定后续结构。前两条容易检验但区分力弱——任何'
        '低熵列都满足；第三条才是本质特征，但它描述的是“因果”，需要转化为'
        '可计算的量。设当前区域的报文矩阵为 $M$、有效位掩码为 $V$，候选字段'
        '位于偏移 $s$、宽度 $w$，第 $i$ 条报文在该字段上的取值为 '
        '$k_i=\\mathrm{val}(M[i,s:s+w])$。定义列集合 $\\mathcal{C}$ 上的'
        '结构一致性为各列众数占比的均值：')
    b.eq_latex(r'\Phi(M,V,\mathcal{C})'
               r'=\frac{1}{|\mathcal{C}|}\sum_{j\in\mathcal{C}}'
               r'\frac{1}{N}\max_{v}\sum_{i=1}^{N}'
               r'\mathbb{I}\!\left[M[i,j]=v\right]', 1)
    b.p('即每一列上“最常见取值所占比例”的平均。按候选字段取值分组后，组内'
        '结构一致性的加权均值为：')
    b.eq_latex(r'\Phi_{\mathrm{in}}(k)=\frac{1}{N}\sum_{u\in\mathcal{K}}'
               r'N_u\,\Phi\!\left(M^{(u)},V^{(u)},\mathcal{C}\right),\quad'
               r'\mathcal{K}=\{k_i\}_{i=1}^{N},\;N_u=|\{i:k_i=u\}|', 2)
    b.p('其中 $M^{(u)}$ 为取值为 $u$ 的报文构成的子矩阵。分组结构增益定义为'
        '组内一致性相对整体的提升：')
    b.eq_latex(r'G(s,w)=\Phi_{\mathrm{in}}(k)-\Phi(M,V,\mathcal{C})', 3)
    b.p('$G>0$ 意味着“知道该字段的取值之后，报文其余部分的排布变得更确定”，'
        '这正是“该字段决定结构”的可计算形式，$G$ 越大判据越强。实现上还需'
        '处理两点：其一是**局部性**，若把整个头部所有列纳入 $\\mathcal{C}$，'
        '长载荷区的随机波动会稀释增益，故同时计算全局增益与“紧随候选字段'
        '之后 10 列”的局部增益并取较大者；其二是**排除项**，可打印字符串'
        '游程内的列与覆盖率不足 95% 的列不参与候选。')
    b.p('最终评分是两类证据的“或”融合：')
    b.eq_latex(r'e_{\mathrm{struct}}=\min\!\left(1,'
               r'\frac{\max(0,G)}{G_0}\right)', 4)
    b.eq_latex(r'e_{\mathrm{type}}=\left(1-H_n(k)\right)\pi(s),\quad '
               r'\pi(s)=\begin{cases}1, & s\leq s_0\\ '
               r'e^{-(s-s_0)/\lambda}, & s>s_0\end{cases}', 5)
    b.eq_latex(r's_{\mathrm{SIF}}=\left[1-(1-e_{\mathrm{struct}})'
               r'(1-\alpha\,e_{\mathrm{type}})\right]'
               r'\left(1-\beta+\beta\min\!\left(1,'
               r'\frac{\Delta}{\Delta_0}\right)\right)'
               r'\left(1-\gamma(w-1)\right)', 6)
    b.p('其中 $H_n$ 为归一化熵，$\\pi(s)$ 为位置先验，$\\Delta$ 为各组'
        '“列确定性指纹”的平均 $L_1$ 距离（组间结构散度），末项为宽度惩罚。'
        '$e_{\\mathrm{type}}$ 刻画“低熵且取值有限”，$e_{\\mathrm{struct}}$ '
        '刻画“分组带来结构确定性提升”，二者缺一不可：只有前者会把常量列'
        '误判为类型码，只有后者会在组数很少时失效。')
    b.p('式（4）~（6）中的 $G_0$、$s_0$、$\\lambda$、$\\alpha$、$\\beta$、'
        '$\\Delta_0$、$\\gamma$ 是**尺度参数**，取值依次为 0.20、8 字节、'
        '8 字节、0.9、0.25、0.3 与 0.1。它们是尺度而非门槛：只把量纲各异的'
        '证据压缩到 $[0,1]$，改动取值只压缩或拉伸评分曲线，不会把“增益为'
        '正”翻转为“为负”。全部尺度参数与决策阈值一并在标定集上选定后固定，'
        '8 个协议共用同一组取值；是否接受一次分裂另由分裂算子上的得分门槛'
        '与增益门槛决定。')
    b.p('**比特级结构标识字段。** 部分协议用若干比特而非整字节标识结构，'
        '例如 IEC 60870-5-104 用控制域的低 2 位区分 I/S/U 帧，此时字节级'
        '判据失效。本文对每个候选字节枚举掩码 '
        '$\\{1,2,4,8,16,32,64,128,3,12,15,240\\}$（8 个单比特与 4 个最常见的'
        '多位段），把掩码后的取值当作分组键重算式（3）；比特级候选的接受'
        '门槛更严（结构证据须 $\\geq 0.45$）且要求掩码后取值种类在 $[2,8]$ '
        '内。比特级字段只标记其所在字节的起始位置，因为在其后再造边界没有'
        '意义。')

    b.h2('4.2 长度字段')
    b.p('长度字段（Length Field，LF）的判定面临三类歧义：宽度歧义（1 字节'
        '还是 2 字节）、偏移歧义（是否吞并了前一字段的尾部）以及巧合歧义'
        '（某些内容字节恰好与报文长度同起同落）。本文用四个统计量加两条'
        '硬约束处理。')
    b.p('（1）**稳健闭合性**。对候选值 $v_i$ 计算残差 $r_i=|m_i|-v_i$。真实'
        '长度字段满足“报文长度减去字段值等于常数”，但真实协议中常有个别'
        '报文带填充、扩展选项或多出一个尾部字段，用标准差会被离群样本抬高'
        '而误判。本文改用中位数附近 $\\pm1$ 的内点占比：')
    b.eq_latex(r'\kappa=\frac{1}{N}\sum_{i=1}^{N}'
               r'\mathbb{I}\!\left[\left|r_i-\mathrm{med}(r)\right|\leq 1\right],'
               r'\quad c_{\mathrm{close}}='
               r'\frac{\kappa}{1+\rho\min(\sigma_r,\sigma_0)}', 7)
    b.p('其中 $\\mathrm{med}(\\cdot)$ 为中位数，$\\sigma_r$ 为残差标准差。内点'
        '占比对少数离群样本不敏感，分母项保留对整体离散程度的惩罚：'
        '$\\rho=0.25$ 是 1 字节离散对应的扣分权重，$\\sigma_0=8$ 是惩罚的饱和'
        '点，两者与式（4）~（6）的尺度参数一并在标定集上选定。')
    b.p('（2）**对齐增益**。把候选字段之后的内容按 $v_i$ 平移后，若该字段'
        '真实指向一个块边界，平移后的首列应高度集中：')
    b.eq_latex(r'A(s,w)=\frac{1}{N}\sum_{i=1}^{N}'
               r'\mathbb{I}\!\left[M[i,s+w+v_i]=u^{\ast}\right]'
               r'-\frac{1}{N}\sum_{i=1}^{N}'
               r'\mathbb{I}\!\left[M[i,s+w]=u^{\prime}\right]', 8)
    b.p('其中 $u^{\\ast}$ 与 $u^{\\prime}$ 分别为两列上的众数，该量度量“按'
        '长度字段平移之后，块的内容是否重新对齐”。（3）**相关性**取 $v_i$ '
        '与报文长度的皮尔逊相关系数，若取值近乎恒定则置零；（4）**结构'
        '边界强度**取字段指向区间内外字节分布的 JS 散度，用于排除“区间'
        '内部与外部同质”的伪长度字段。')
    b.p('在此之上增加两条硬约束。其一是**自然对齐**：候选字段的起始偏移'
        '必须是其宽度的整数倍，这消除了“把上一字段尾部并入长度字段”造成的'
        '宽度歧义（例如把 Modbus/TCP 的 2 字节协议标识 0x0000 与其后的 '
        '2 字节长度合并成 4 字节“长度”）。其二是**取值序列去重**：若同一'
        '取值序列可由不同宽度解释，取自然对齐下更宽的解释，因为多字节长度'
        '字段的高字节常恒为 0。单字节候选另要求取值基数不低于 3。长度字段'
        '还须排除可打印游程，否则文本中恰与报文长度近似闭合的字节会触发'
        '连锁的伪垂直分裂。')

    b.h2('4.3 可直接验证的语义锚点')
    b.p('MSERA 等工作总结了工控协议典型语义字段的数据特征：协议标识、'
        '长度、序列号、校验和、时间戳、功能码等' + C('msera') + '。这些特征'
        '的可信程度并不相同：**可直接验证**的语义（校验和、严格递增序号、'
        '与抓包时间线性相关的时间戳）可用确定性算法判定，误差主要来自阈值'
        '而非模型假设，故可作为硬约束直接给出区间；**只能提示存在性**的'
        '语义（协议标识、常量游程）只说明“此处可能有一个字段”，其精确区间'
        '仍需数据支撑，故只作为软证据。')
    b.p('校验和用前缀增量扫描检测。传统做法只在报文尾部比对，只能覆盖“整'
        '报文一个校验尾”的情形；而 DNP3 这类协议在每个数据块之后都插入一个 '
        'CRC16，校验值出现在报文中部且位置随报文长度变化。本文对每个候选'
        '位置 $p$ 与宽度 $w$ 检验 $m[p:p+w]=\\mathrm{CRC}(m[:p])$，并用前缀'
        '增量计算把复杂度从 $O(L^2)$ 降到 $O(L)$。同时排除退化匹配：若前缀'
        '在各报文间几乎不变，其校验值也几乎不变，会与该位置上任何近乎恒定'
        '的字节自动吻合，故要求校验值至少有 3 个不同取值。实现覆盖 CRC-16'
        '（含 CCITT、XMODEM、MODBUS、DNP 等参数化）、CRC-32 与单字节累加和/'
        '异或和，并按字节序同时尝试大端与小端。')
    b.p('序列号的判据是**严格递增 1**：同一方向相邻报文差值恰为 1 的比例'
        '超过 85%，且该字段至少有 4 个不同取值；若允许“差值 0 或 1”，任何'
        '变化缓慢的类型码都会被判成序列号。时间戳的判据是与抓包时间戳的'
        '相关系数不低于 0.95，宽度为 4 或 8 字节。协议标识取起始 1~2 字节的'
        '短常量签名；若向后延伸，会把紧随其后、高字节恰为常量的长度字段'
        '吞进来（如 TPKT 的 version|reserved|长度高字节），故只作为软证据。')

    # ==================== 5 递归分裂 ====================
    b.h1('5 关键字段驱动的递归分裂')
    b.p('本节把第 4 节的关键字段转化为对报文集合的分裂算子。核心问题是：'
        '在什么条件下可以用一个字段把区域一分为二（或多分），分裂之后'
        '哪些结论可以跨子区域继承，哪些必须重新估计。')
    b.h2('5.1 区域、分裂算子与不变式')
    b.p('把**区域**定义为一个二元组 $\\mathcal{R}=(S_{\\mathcal{R}},'
        '[a,b))$，其中 $S_{\\mathcal{R}}\\subseteq S$ 是报文子集，$[a,b)$ 是'
        '该子集共同考察的偏移区间。分裂算子 $\\mathrm{Split}(\\cdot)$ 把'
        '区域映射为若干子区域：')
    b.eq_latex(r'\mathrm{Split}(\mathcal{R})=\{\mathcal{R}_1,\dots,'
               r'\mathcal{R}_K\},\quad '
               r'\bigcup_{k}\mathcal{R}_k=\mathcal{R},\quad '
               r'\mathcal{R}_k\cap\mathcal{R}_{k^{\prime}}'
               r'=\varnothing\;(k\neq k^{\prime})', 9)
    b.p('分裂可以是**水平的**（按字段取值把报文分桶，子区域共享同一偏移'
        '区间）或**垂直的**（按字段指向的区间把偏移区间切段，子区域共享'
        '同一报文子集）。两者都不改变目标，只改变推断所依据的样本集合。'
        '分裂必须维持一条不变式：**子区域内部结构同质且偏移一致**——'
        '结构同质指子集内不再混有不同类型，偏移一致指同一字段在子集内各'
        '报文的起始偏移相同。这条不变式是后续列统计量有意义的前提，也是'
        '判断一次分裂是否成功的标准：若分裂之后区域的列确定性没有提高，'
        '说明分错了。')
    b.p('实现上通过三个动作维持不变式：子区域重新计算有效列与列统计量，'
        '不继承父区域结果；子区域重新识别关键字段，因为父区域的判据在子集'
        '上未必成立；子区域偏移从 0 重新计数，使统计量始终定义在“相对本'
        '区域的列”上。')

    b.h2('5.2 水平分裂')
    b.p('设区域 $\\mathcal{R}$ 上识别出结构标识字段 $f$（偏移 $s$、宽度 '
        '$w$），按取值把报文分桶：')
    b.eq_latex(r'\mathcal{R}_u=\left(S_u,\,[a,b)\right),\quad '
               r'S_u=\{i\in S_{\mathcal{R}}:k_i=u\},\quad '
               r'u\in\mathcal{K}', 10)
    b.p('对字节级字段 $k_i=M[i,s:s+w]$；对比特级字段，$k_i$ 取掩码后的比特'
        '值。分桶之后每个桶内部结构同质，列统计量重新可比，但桶与桶之间仍'
        '可能共用字段，因此桶内还需继续识别关键字段（5.5 节）。')
    b.p('为使分裂有意义，对分桶附加四条约束：桶数 $K$ 落在 $[2,12]$ 内——'
        '太少则异构未被充分消除，太多则每桶样本过少、列确定性会因抽样波动'
        '“假性”升高；至少有 2 个桶的报文数不少于 $m_g$（取 4）；当前区域'
        '报文数不少于 $2m_g$；同一 $(a,s,w)$ 三元组只允许分裂一次，以防在'
        '同一偏移上反复分桶造成循环（这在比特级掩码枚举下尤为必要）。水平'
        '分裂的代价是 $O(NL)$，收益是把混合分布拆成若干同质分布。以 MQTT '
        '为例：三类报文的固定头之后字段排布完全不同，若不分裂，主题串的'
        '长度差异会与报文类型差异混在同一列上；按首字节低 4 位分桶后，'
        'PUBLISH 桶内“主题长度—主题串—报文标识”的顺序才稳定下来。')
    b.p('水平分裂有一条隐含前提：结构标识字段在所有结构上处于同一偏移。'
        '对多层封装协议，内层同名字段在不同报文间未必对齐——同一偏移在 A '
        '结构上是 COTP 参数码，在 B 结构上可能落在 S7 头内部，按该偏移分桶'
        '反而会把不同的内层结构混进同一个桶。本文的应对是块内不使用结构'
        '标识字段，并把分裂深度限制在 3 层，使偏移漂移在逐层剥离中被消除。'
        '若要直接作用到内层，需先做“区域对齐”，这不在本文范围内。')

    b.h2('5.3 垂直分裂')
    b.p('设区域 $\\mathcal{R}$ 上识别出长度字段 $f$（偏移 $s$、宽度 $w$），'
        '第 $i$ 条报文的取值为 $v_i$。把该报文在 $[a,b)$ 内切成三段：')
    b.eq_latex(r'[a,\,s)\ |\ [s,\,s+w)\ |\ '
               r'[s+w,\,s+w+v_i)\ |\ '
               r'[s+w+v_i,\,b)', 11)
    b.p('对应的三个子区域为前置段 $(S_{\\mathcal{R}},[a,s))$、块 '
        '$(S_{\\mathcal{R}},[s+w,s+w+v_i))$ 与余部 '
        '$(S_{\\mathcal{R}},[s+w+v_i,b))$。块与余部的起始偏移随 $v_i$ 变化，'
        '因此这两个子区域在实现上不是“切一段固定区间”，而是把每条报文的'
        '对应片段左对齐后重新组成矩阵。这正是消除偏移漂移的操作：块内字段'
        '不再受前置段长度影响，余部字段不再受块长度影响。三条分界线同时'
        '成为边界证据：$s$（前置段与长度字段的交界）、$s+w$（长度字段与块'
        '起点）与 $s+w+v_i$（块尾）；前两条对所有报文相同，第三条逐报文'
        '不同，是本文少数几个“逐报文给出不同边界”的位置，也是块作为变长'
        '字段的直接体现。')
    b.p('块的处理需要额外约束：块通常是同一个变长字段（字符串、数组、嵌套'
        '报文）的内容，其中检出的“结构标识字段”多半是内容字节的巧合，因此'
        '**块内只把长度字段当作边界锚点**，结构标识字段仅在根区域、前置段'
        '与余部中生效。块内仍优先尝试再次识别长度字段，以支持多层封装'
        '（如 TPKT→COTP→S7comm）的逐层剥离：外层长度字段指向的块恰好是'
        '内层报文，块内再次识别长度字段即可继续下剥，直到块内不再存在满足'
        '门槛的长度字段为止。对定长报文，$v_i$ 在各报文上相同，垂直分裂'
        '退化为在固定位置切三刀，其主要作用是把块与头部解耦，避免块内的'
        '高熵内容污染头部的列统计。')
    fig2 = FIG / 'fig2_split.png'
    if fig2.exists():
        b.figure(str(fig2), '图 2　水平分裂与垂直分裂的作用', width_twips=8600)

    b.h2('5.4 递归、终止与端点标记时机')
    b.p('分裂在四种情形下终止：达到最大深度（取 3）；区域报文数少于 4；'
        '区域内所有报文字节串完全相同；既无满足门槛的结构标识字段也无满足'
        '门槛的长度字段。终止时转入叶子推断（第 6 节），并把该区域检出的'
        '关键字段端点全部标记为边界。')
    b.p('“何时标记关键字段端点”是一个容易被忽略但影响很大的设计点。关键'
        '字段的端点只有在**结构同质**的区域上才对全部报文成立。若在某层'
        '已决定继续分裂，却仍把该层检出的所有候选端点标记到全部报文上，'
        '就会把 A 结构的字段端点错标到 B 结构报文的某个大字段内部，在头部'
        '重叠区造出成片伪边界。因此本文的规则是：**若本层继续分裂，只标记'
        '被用作分裂键的那个字段**（它在所有结构上位于同一偏移，其端点对'
        '全部报文成立）；其余候选留给各子结构重新识别；只有在叶子区域才做'
        '广度标记。')
    b.p('这条规则同时解释了为什么分裂深度需要受限。深度每增加一层，区域内'
        '的报文数至少减少一半（水平分裂）或区域长度至少减少一个块（垂直'
        '分裂），统计量的可靠性随之下降；深度过大还会使“关键字段在全部'
        '结构上同偏移”这一前提在多层封装协议上失效。深度限制在 3 层，是在'
        '“剥离多层封装”与“保持样本量”之间的折中。整个流程的复杂度为 '
        '$O(D\\cdot N\\cdot L)$（$D$ 为最大深度），万级报文仍可在数秒内完成。')

    b.h2('5.5 跨结构语义共享与迁移')
    b.p('即使经过水平分裂，不同结构的报文仍会共用部分字段——这是协议设计'
        '为简化实现而做的复用。本文设置两条机制利用这一现象。**机制 A'
        '（分裂键复用）**：被选作分裂键的结构标识字段在全部结构上位于同一'
        '偏移，因此它在根区域被识别一次之后，其端点对所有结构都成立，无需'
        '在每个子结构上重复识别。**机制 B（本地验证后的迁移）**：水平分裂后'
        '各结构独立推断关键字段，容易出现“样本多的结构检出稳定、样本少的'
        '结构漏检”的不均衡，为此在分裂完成后增加第二遍——对每个结构 $G$，'
        '取兄弟结构上得分不低于 0.6 的关键字段 $f$，在 $G$ 上做本地验证，'
        '通过才把 $f$ 的端点补为 $G$ 的边界。')
    b.p('验证判据依字段类型而定：若 $f$ 是长度字段，要求残差内点占比不低于 '
        '0.9 且取值有变化，即')
    b.eq_latex(r'\kappa_{G}(f)\geq 0.9\ \ \wedge\ \ '
               r'\left|\{v_i^{(G)}\}\right|>1', 12)
    b.p('若 $f$ 是结构标识字段，要求其取值基数落在 $[2,20]$ 内且覆盖率不'
        '低于 60%。两个条件的含义相同：迁移过去的假设必须在本结构**自己的'
        '数据**上重新成立，而不是仅凭兄弟结构的证据。这一设计的关键在于'
        '“验证”而非“照搬”，因此既能补上小样本结构的漏检，又不会把兄弟'
        '结构的错误带过来。报文起始处的常量前缀虽可跨结构共享，但其区间常'
        '横跨多个真实字段（如 TPKT 的 version/reserved/长度高字节），故只'
        '用于给端点，不参与“区间内部禁止切分”的软约束。')

    # ==================== 6 证据融合与解码 ====================
    b.h1('6 边界证据融合与最大后验解码')
    b.h2('6.1 位置级证据特征')
    b.p('在叶子区域上，对每个候选切分位置 $p\\in[1,L)$ 计算 18 维特征。'
        '特征的设计遵循一条原则：单个特征都可能被个别协议欺骗，但“结构'
        '变化”“取值依赖”“语义锚点”三类证据同时成立时，误判概率很低。'
        '为便于后文引用，表 1 给出每个特征的记法、定义与判别方向，其中 '
        '$\\mathrm{det}(j)$ 表示第 $j$ 列的众数占比，$H_n(j)$ 表示第 $j$ 列'
        '的归一化熵，$\\mathrm{MI}$ 表示两列的互信息。')
    b.table('表 1　位置级切分证据特征（$p$ 为候选切分位置，两侧指 $p-1$ 与 $p$ 列）',
            ['类别', '记法', '含义与判别方向'],
            [['取值依赖', '$1-\\rho_p$', '两侧列互信息的归一化补，越接近 1 越可能是边界'],
             ['', '$\\rho_p$', '两侧列的归一化互信息（耦合度），越高越可能同属一个字段'],
             ['', '$\\mathrm{MI}_p$', '两侧列的原始互信息，用于区分耦合的绝对强度'],
             ['', '$\\Delta\\mathrm{det}_p$', '两侧列众数占比之差，突变处倾向边界'],
             ['', '$\\mathrm{det}_{p-1},\\ \\mathrm{det}_p$', '左、右列的众数占比绝对值'],
             ['', '$\\beta_p$', '常量断裂标志：一侧恒定而另一侧变化时取 1'],
             ['分布变化', '$\\Delta H_p$', '两侧列归一化熵之差，熵跃升处倾向边界'],
             ['', '$H_p$', '右侧列的归一化熵'],
             ['', '$\\bar{H}_{\\mathrm{L}},\\ \\bar{H}_{\\mathrm{R}}$',
              '左、右各 4 列的平均归一化熵，刻画局部平稳性'],
             ['结构变化', '$\\ell_p$', '左侧连续恒定列的长度（上限截断为 4）'],
             ['', '$\\varepsilon_p$', '是否靠近区域首尾（$p\\leq2$ 或 $L-p\\leq2$）'],
             ['', '$p/L$', '相对位置，用于抑制载荷区远端的偶然突变'],
             ['内容性质', '$\\pi_p$', '是否为载荷区起点'],
             ['', '$\\sigma_p$', '两侧是否同处一个可打印字符串游程内'],
             ['语义锚点', '$\\alpha_p$', '是否为语义字段的起点'],
             ['', '$\\iota_p$', '是否落在语义字段内部（落在内部时抑制切分）']],
            [1100, 2200, 5300])
    b.p('这 18 个特征并非同权：把它们线性组合为一个标量分数，即位置 $p$ 的'
        '切分对数几率')
    b.eq_latex(r'z_p=\mathbf{w}^{\top}\mathbf{x}_p+b,\quad '
               r'\mathbf{x}_p\in\mathbb{R}^{18}', 13)
    b.p('其中 $\\mathbf{w}$ 与 $b$ 由逻辑回归在标定集上以“是否为参考边界”'
        '为标签训练得到，评测集不参与，以保证比较的公平性。')
    b.h2('6.2 字段宽度先验及其作用')
    b.p('协议头部字段以 1~4 字节为主，8 字节（时间戳、双精度浮点）次之，'
        '超长字段主要出现在载荷区。据此给出字段宽度的对数先验：')
    b.eq_latex(r'\log P(w)=\begin{cases}'
               r'-0.50, & w=1\\ -0.42, & w=2\\ -0.95, & w=4\\ '
               r'-1.35, & w=3\\ -1.25, & w=8\\ '
               r'-1.9-1.05\ln w, & w\geq 9\end{cases}', 14)
    b.p('其中 5~7 字节取 $-2.1\\sim-2.3$（按插值处理）。幂律尾部让“整段'
        '载荷作为一个长字段”仍保有可观的先验概率，避免解码器把载荷强行'
        '切碎。')
    b.p('这一先验的作用是**正则化**，而不是“事后校验切分是否符合常见'
        '宽度”。若当作事后校验（先按证据切分、再检查宽度是否合理），一旦'
        '某处切错，后续位置会为“凑出常见宽度”继续错切，误差沿报文单向'
        '累积。本文把先验与证据放进**同一个目标函数**联合优化（6.3 节），'
        '先验只通过边界左右两段的宽度差进入目标，不改变位置级得分 $z_p$，'
        '故证据强处不会被“挪动”，只可能被“否决”；又因 $\\log P(w)$ 关于 '
        '$w$ 单调不增，合并两段总比切开划算，先验从不会**强迫**产生新边界，'
        '只会在证据不足时**阻止**它。其失效模式因此被限制为“漏切一条边界”'
        '（局部、有界），而非“为满足宽度分布而连切数刀”（全局、发散）。')
    b.h2('6.3 最大后验解码')
    b.p('把切分点集合记作 $F$，则最优切分由下式给出：')
    b.eq_latex(r'F^{\ast}=\underset{F}{\mathrm{arg\,max}}\ \sum_{p\in F}'
               r'\left(z_p-\theta\right)'
               r'+\sum_{w\in\mathcal{W}(F)}\log P(w)', 15)
    b.p('其中 $\\theta$ 为决策阈值，$\\mathcal{W}(F)$ 为由 $F$ 诱导出的各段'
        '宽度集合。式（15）在“切分收益”与“字段过碎或过粗的代价”之间取得'
        '平衡，且可用动态规划在 $O(L\\,w_{\\max})$ 时间内精确求解：')
    b.eq_latex(r'\mathrm{best}[j]=\max_{1\leq w\leq w_{\max}}'
               r'\left\{\mathrm{best}[j-w]+\log P(w)'
               r'+\mathbb{I}[j-w>0]\left(z_{j-w}-\theta\right)\right\}', 16)
    b.p('其中 $\\mathrm{best}[j]$ 为前缀 $[0,j)$ 的最优得分，'
        '$w_{\\max}$ 为最大字段宽度。动态规划对每个位置只保留最优前驱，'
        '得到的是全局最优解而非贪心解，这对抑制“局部证据偶然偏强导致的'
        '错误切分”很关键。阈值 $\\theta$ 不调整单个位置的判决，而是在全局'
        '上控制字段的平均宽度：$\\theta$ 越大，解码越倾向合并相邻两段。'
        '$\\theta$ 在独立于评测集的开发集上选定，全部实验共用同一取值。')
    b.h2('6.4 覆盖度截断')
    b.p('垂直分裂后的余部长度随报文变化，靠后的列可能只有少数长报文覆盖。'
        '在这些列上做切分会把个别长报文的内部结构强加给全部报文，产生成片'
        '误报。为此定义第 $c$ 列的覆盖度并据此截断有效列：')
    b.eq_latex(r'\mathrm{cov}(c)=\frac{1}{N}\sum_{i=1}^{N}'
               r'\mathbb{I}\left[c<|m_i|\right],\quad '
               r'L_c=\max\left\{c:\mathrm{cov}(c)\geq c_{\min}\right\}+1', 17)
    b.p('只允许在 $c<L_c$ 的列上切分，超出部分视为“该区域的共同前缀已经'
        '结束”。图 3 给出一个例子：某余部区域 10 条报文的长度从 34 到 52 '
        '字节不等，覆盖度随列偏移单调下降；当 $c_{\\min}=0.6$ 时截断点为 '
        '$L_c=41$，其后的 11 列仅有 5 条以内的长报文有内容。若不加截断，'
        '这些列上的切分会以 5 条报文的结构去推断另外 5 条报文不存在的字段，'
        '产生的切分点被计入后者误报。')
    fig3 = FIG / 'fig3_coverage.png'
    if fig3.exists():
        b.figure(str(fig3), '图 3　覆盖度截断示例（$c_{\\min}=0.6$，'
                            '截断点 $L_c=41$）', width_twips=8400)
    b.p('截断的代价是可能漏掉长报文尾部的真实边界，故 $c_{\\min}$ 不宜过高。'
        '敏感性分析表明，$c_{\\min}$ 在 0.4~0.9 之间变化时 F1 的极差不足 '
        '0.2 个百分点：“是否截断”比“截断在哪里”更重要。')

